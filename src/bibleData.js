const translationSources = {
  KRV: { directory: 'gae', sourceId: 'GAE' },
  RNKSV: { directory: 'rnksv', sourceId: 'RNKSV' },
};

const BIBLE_CACHE_NAME = 'bibleon-bible-v1';
const bookCache = new Map();

async function fetchBibleResource(resourceUrl) {
  if (!('caches' in window)) return fetch(resourceUrl);

  try {
    const cache = await window.caches.open(BIBLE_CACHE_NAME);
    const cachedResponse = await cache.match(resourceUrl);
    if (cachedResponse) return cachedResponse;

    const response = await fetch(resourceUrl);
    if (response.ok) await cache.put(resourceUrl, response.clone());
    return response;
  } catch {
    return fetch(resourceUrl);
  }
}

async function loadBibleBook(translationId, book) {
  const translationSource = translationSources[translationId];
  if (!translationSource) throw new Error(`Unknown Bible translation: ${translationId}`);

  const cacheKey = `${translationId}:${book.file}`;
  let data = bookCache.get(cacheKey);
  if (data) return data;

  const baseUrl = import.meta.env.BASE_URL ?? '/';
  const response = await fetchBibleResource(`${baseUrl}data/bible/${translationSource.directory}/${book.file}.json`);
  if (!response.ok) throw new Error(`Failed to load ${translationId} ${book.name}`);
  data = await response.json();
  if (data.translation?.id !== translationSource.sourceId || data.book?.id !== book.id) {
    throw new Error(`Invalid Bible data: ${translationId} ${book.name}`);
  }
  bookCache.set(cacheKey, data);
  return data;
}

export async function loadBibleChapter(translationId, bookId, chapterNumber) {
  const book = bibleCatalog.find((item) => item.id === bookId);
  if (!book) throw new Error(`Unknown Bible book: ${bookId}`);

  const data = await loadBibleBook(translationId, book);

  const chapter = data.chapters.find((item) => item.chapter === chapterNumber);
  if (!chapter) throw new Error(`Missing chapter: ${book.name} ${chapterNumber}`);
  return chapter.verses;
}

export async function searchBibleVerses(translationId, query, limit = 30) {
  const normalizedQuery = query.trim().toLocaleLowerCase('ko-KR').replace(/\s+/g, ' ');
  if (!normalizedQuery) return [];

  const books = await Promise.all(bibleCatalog.map(async (book) => ({
    book,
    data: await loadBibleBook(translationId, book),
  })));
  const results = [];

  for (const { book, data } of books) {
    for (const chapter of data.chapters) {
      for (const verse of chapter.verses) {
        if (!verse.text.toLocaleLowerCase('ko-KR').replace(/\s+/g, ' ').includes(normalizedQuery)) continue;
        results.push({
          bookId: book.id,
          bookName: book.name,
          chapter: chapter.chapter,
          verse: verse.verse,
          reference: `${book.name} ${chapter.chapter}:${verse.verse}`,
          text: verse.text,
        });
        if (results.length >= limit) return results;
      }
    }
  }

  return results;
}

export async function getBibleVerseCount(translationId = 'KRV') {
  const books = await Promise.all(bibleCatalog.map((book) => loadBibleBook(translationId, book)));
  return books.reduce((total, book) => (
    total + book.chapters.reduce((bookTotal, chapter) => bookTotal + chapter.verses.length, 0)
  ), 0);
}

export async function preloadBible(
  translationIds = Object.keys(translationSources),
  onProgress = () => {},
  concurrency = 6,
) {
  const booksToLoad = translationIds.flatMap((translationId) => (
    bibleCatalog.map((book) => ({ translationId, book }))
  ));
  const total = booksToLoad.length;
  let completed = 0;
  let nextBookIndex = 0;

  onProgress(completed, total);

  const loadNextBook = async () => {
    while (nextBookIndex < total) {
      const bookIndex = nextBookIndex;
      nextBookIndex += 1;
      const { translationId, book } = booksToLoad[bookIndex];
      await loadBibleBook(translationId, book);
      completed += 1;
      onProgress(completed, total);
    }
  };

  const workerCount = Math.max(1, Math.min(concurrency, total));
  await Promise.all(Array.from({ length: workerCount }, loadNextBook));
}
